// Writes tools/mgba/rr_calc_names.lua: Radical Red species, move, item and ability names spelled
// the way hzla's Dynamic-Calc-Decomps damage calc spells them, so the Showdown export pastes into
// the calc cleanly. Species, moves and items come from the calc's own RR save-reader tables
// (indexed by RR ID). Abilities come from the ROM's ability name table at 0x090E32C0 (17 bytes
// each, see tools/rom/ability_ids.py), renamed to the spelling in the calc's RR ability list
// (calc/data/abilities.js, which the import checks names against) when they match after dropping
// case, spaces and punctuation. The ROM truncates some names; ABILITY_FIXES covers the ones that
// do not match that way (the two As One IDs: 73 is Calyrex-Shadow's, 77 Calyrex-Ice's, from the
// ROM base stats table).
// Usage: node tools/mgba/gen_calc_names.js <rr.gba> [out.lua]
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const SITE = 'https://hzla.github.io/Dynamic-Calc-Decomps/';
const FILES = {
  constants: 'js/savereaders/save_constants/radical_red_constants.js',
  items: 'js/savereaders/save_constants/radical_red_item_constants.js',
  abilities: 'calc/data/abilities.js',
};
// Entries after 281 (Tera Shell) are battle text, not ability names.
const ABILITY_NAMES = 0x090E32C0, ABILITY_NAME_SIZE = 17, ABILITY_COUNT = 282;
const ABILITY_FIXES = {
  73: 'As One (Spectrier)', 74: 'Neutralizing Gas', 77: 'As One (Glastrier)',
  164: 'Wandering Spirit', 204: 'Electromorphosis',
};

// The files are UMD or CommonJS modules: run each with a CommonJS `module` and take its exports.
// abilities.js requires ../util only for toID.
async function load(file) {
  const res = await fetch(SITE + file);
  if (!res.ok) throw new Error(file + ': HTTP ' + res.status);
  const module = { exports: {} };
  const sandbox = { module, exports: module.exports, require: () => ({ toID: clean }), globalThis: {} };
  vm.runInNewContext(await res.text(), sandbox, { filename: file });
  return module.exports;
}

function romAbilityNames(rom) {
  const chars = { 0x00: ' ', 0xAB: '!', 0xAC: '?', 0xAD: '.', 0xAE: '-', 0xB4: "'", 0xB8: ',', 0xBA: '/' };
  for (let i = 0; i < 10; i++) chars[0xA1 + i] = String(i);
  for (let i = 0; i < 26; i++) {
    chars[0xBB + i] = String.fromCharCode(65 + i);
    chars[0xD5 + i] = String.fromCharCode(97 + i);
  }
  const names = [];
  for (let id = 0; id < ABILITY_COUNT; id++) {
    const o = ABILITY_NAMES - 0x08000000 + id * ABILITY_NAME_SIZE;
    let s = '';
    for (let i = 0; i < ABILITY_NAME_SIZE && rom[o + i] !== 0xFF; i++) s += chars[rom[o + i]] ?? '?';
    names.push(s.trim());
  }
  return names;
}

const clean = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, '');
const lua = (s) => JSON.stringify(s);

function luaList(name, list, skip) {
  const out = ['M.' + name + ' = {'];
  list.forEach((v, id) => {
    if (v && !skip(v)) out.push('  [' + id + '] = ' + lua(v) + ',');
  });
  out.push('}');
  return out.join('\n');
}

async function main() {
  const [romPath, outPath = path.join(__dirname, 'rr_calc_names.lua')] = process.argv.slice(2);
  if (!romPath) throw new Error('usage: node gen_calc_names.js <rr.gba> [out.lua]');
  const rom = fs.readFileSync(romPath);
  const constants = await load(FILES.constants);
  const items = (await load(FILES.items)).items;

  const calcAbilities = new Map();
  for (const a of (await load(FILES.abilities)).ABILITIES[8]) calcAbilities.set(clean(a), a);
  const abilities = romAbilityNames(rom).map((n, id) => ABILITY_FIXES[id] || calcAbilities.get(clean(n)) || n);
  const unmatched = abilities.filter((n, id) => id > 0 && !calcAbilities.has(clean(n)));

  const lines = [
    '-- Generated by tools/mgba/gen_calc_names.js on ' + new Date().toLocaleDateString('en-CA') + '. Do not edit by hand.',
    '-- Species, move and item names by Radical Red ID: from hzla\'s Dynamic-Calc-Decomps save reader',
    '-- (https://github.com/hzla/Dynamic-Calc-Decomps), files ' + SITE + FILES.constants,
    '-- and ' + SITE + FILES.items + '.',
    '-- Ability names by RR ID: the ROM\'s ability name table at 0x090E32C0, spelled as in',
    '-- ' + SITE + FILES.abilities + ' (RR list).',
    '',
    'local M = {}',
    '',
    luaList('species', constants.mons, (v) => v === '-----'),
    '',
    luaList('moves', constants.moves, (v) => v === '(No Move)'),
    '',
    luaList('items', items, (v) => v === 'None' || v === '?????' || v.startsWith('Free Space')),
    '',
    luaList('abilities', abilities, (v) => v === '-------' || v === ''),
    '',
    'return M',
    '',
  ];
  fs.writeFileSync(outPath, lines.join('\n'));
  console.log('wrote', outPath, 'species', constants.mons.length, 'moves', constants.moves.length,
    'items', items.length, 'abilities', abilities.length);
  console.log('ROM abilities with no calc spelling:', unmatched.join(', ') || 'none');
}

main().catch((e) => { console.error(e.message); process.exit(1); });
